// Release signing comes from the environment, so no key is ever stored in the repository.
// Without a key the release build is signed with the debug key, so it installs but is only a community build.
val keystorePath: String? = System.getenv("KEYSTORE_PATH")

android {
    namespace = "com.ashu.ashutool"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.ashu.ashutool"
        minSdk = 26
        targetSdk = 34
        versionCode = 3
        versionName = "2.0.0"
        // SHA-256 of the author's signing certificate. Set it when building the official release, see README.
        // Left empty, the app reports itself as a community build.
        buildConfigField("String", "CERT_SHA256", "\"${System.getenv("CERT_SHA256") ?: ""}\"")
    }
    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }
    buildTypes {
        release {
            // Shrinks and renames the code, which also makes the app harder to take apart and repackage
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android.txt"), "proguard-rules.pro")
            signingConfig = if (keystorePath != null) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

